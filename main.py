# =====================================================================
# Это ГЛАВНЫЙ файл программы. Именно его запускает человек.
# Простыми словами:
#   - здесь мы "включаем" окно программы,
#   - применяем тёмную тему (чтобы было красиво),
#   - показываем главное окно и ждём, пока пользователь его закроет.
# Чтобы запустить программу, нужно выполнить:  python main.py
# =====================================================================

import sys  # sys нужен, чтобы передать программе аргументы запуска и правильно выйти
from PyQt6.QtWidgets import QApplication  # QApplication - "двигатель" любого окна на PyQt

from main_window import MainWindow  # MainWindow - наше главное окно (описано в файле main_window.py)
from style import DARK_STYLE  # DARK_STYLE - просто текст с описанием тёмных цветов


def run_gui():
    # Создаём приложение. Без этой строчки окна вообще не появятся.
    app = QApplication(sys.argv)
    # Применяем тёмную тему ко всем кнопкам, таблицам и окнам сразу.
    app.setStyleSheet(DARK_STYLE)
    # Создаём главное окно (все 7 вкладок живут именно там).
    window = MainWindow()
    # Показываем окно на экране (до этого оно было создано, но невидимо).
    window.show()
    # Запускаем "бесконечный круг": программа ждёт клики, нажатия клавиш и т.д.
    # Когда окно закроют - выходим из Python.
    sys.exit(app.exec())


# Эта проверка означает: "если файл запустили напрямую, а не подключили как библиотеку".
# То есть код ниже сработает только при запуске python main.py
if __name__ == "__main__":
    run_gui()